local sl = {}

local function slog(fmt, ...)
	local line = select("#", ...) > 0 and fmt:format(...) or fmt
	ForeverDevInfoDB = ForeverDevInfoDB or {}
	ForeverDevInfoDB.soundLoad = ForeverDevInfoDB.soundLoad or {}
	local l = ForeverDevInfoDB.soundLoad
	l[#l + 1] = date("%H:%M:%S") .. " " .. line
	while #l > 200 do table.remove(l, 1) end
	print("|cff33ff99FDI sounds|r " .. line)
end

local function sampleFps(label, seconds, done)
	local samples = {}
	local ticker
	ticker = C_Timer.NewTicker(1, function()
		samples[#samples + 1] = GetFramerate()
		if #samples >= seconds then
			ticker:Cancel()
			local sum, lo = 0, math.huge
			for _, v in ipairs(samples) do sum = sum + v; lo = math.min(lo, v) end
			slog("%s: fps avg %.1f, lowest %.1f over %d s", label, sum / #samples, lo, #samples)
			if done then done() end
		end
	end)
end

local function register()
	if sl.ids then slog("already registered - /fdsoundload off first"); return end
	if InCombatLockdown() then slog("out of combat, please"); return end
	if not (C_UnitAuras and C_UnitAuras.AddAuraSound and Enum.UnitAuraSoundTrigger) then slog("AddAuraSound missing"); return end
	slog("[run] measuring the frame rate for 10 s first - stand still")
	sampleFps("before", 10, function()
		local ids, fails, firstErr = {}, 0, nil
		local memBefore = collectgarbage("count")
		local t0 = debugprofilestop()
		for kind, list in pairs(LISTS) do
			for _, id in ipairs(list) do
				local ok, sid = pcall(C_UnitAuras.AddAuraSound, Enum.UnitAuraSoundTrigger.Added,
					{ unitToken = "player", spellID = id, soundFileName = SOUNDS[kind], outputChannel = "Master", throttleSeconds = 0.5 })
				if ok and type(sid) == "number" then ids[#ids + 1] = sid
				else fails = fails + 1; firstErr = firstErr or tostring(sid) end
			end
		end
		local ms = debugprofilestop() - t0
		sl.ids = ids
		slog("registered %d aura sounds in %.1f ms (%d failed%s); Lua memory %+.0f KB",
			#ids, ms, fails, firstErr and (": " .. firstErr) or "", collectgarbage("count") - memBefore)
		sampleFps("after", 10, function()
			slog("done. Now fight: murloc Frostbolt = air horn, spider poison = bike horn, curses = cow, diseases = cat.")
		end)
	end)
end

local function unregister()
	if not sl.ids then slog("nothing registered"); return end
	local t0 = debugprofilestop()
	for _, sid in ipairs(sl.ids) do pcall(C_UnitAuras.RemoveAuraSound, sid) end
	slog("removed %d aura sounds in %.1f ms", #sl.ids, debugprofilestop() - t0)
	sl.ids = nil
end

SLASH_FOREVERDEVSOUNDLOAD1 = "/fdsoundload"
SlashCmdList["FOREVERDEVSOUNDLOAD"] = function(msg)
	if (msg or ""):lower():match("off") then unregister() else register() end
end
